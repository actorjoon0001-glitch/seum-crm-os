create table if not exists public.crm_activity_logs (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  kind        text not null,      -- login / auto_login / login_failed / logout / delete
  actor       text,               -- 로그인한 사람 이름
  role        text,               -- owner(관리자) / staff(직원)
  detail      text,
  ip          text,
  user_agent  text
);

create index if not exists crm_activity_logs_created_idx on public.crm_activity_logs (created_at desc);

alter table public.crm_activity_logs enable row level security;
